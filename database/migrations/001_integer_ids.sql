-- One-off conversion of UUID keys to BIGINT identity keys (users numbered in sign-up order).
-- Runs only while users.id is still a UUID; on every later run it does nothing.
-- migrate.js runs this before schema.sql, inside the same transaction, so a failure changes nothing.
-- Indexes on converted columns are dropped with the old columns and recreated by schema.sql.

-- Swaps a column holding user UUIDs for one holding the new user numbers
CREATE OR REPLACE FUNCTION pg_temp.vl_remap_user_column(tbl TEXT, col TEXT) RETURNS VOID
LANGUAGE plpgsql AS $f$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = tbl AND column_name = col AND data_type = 'uuid'
  ) THEN
    RETURN;
  END IF;
  EXECUTE format('ALTER TABLE public.%I ADD COLUMN %I BIGINT', tbl, col || '_new');
  EXECUTE format('UPDATE public.%I t SET %I = m.new_id FROM vl_user_id_map m WHERE t.%I = m.old_id', tbl, col || '_new', col);
  -- Also drops the primary keys, checks and indexes that include the old column
  EXECUTE format('ALTER TABLE public.%I DROP COLUMN %I', tbl, col);
  EXECUTE format('ALTER TABLE public.%I RENAME COLUMN %I TO %I', tbl, col || '_new', col);
END
$f$;

-- Replaces a table's UUID id with an identity column, numbered by created_at
CREATE OR REPLACE FUNCTION pg_temp.vl_renumber(tbl TEXT) RETURNS VOID
LANGUAGE plpgsql AS $f$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = tbl AND column_name = 'id' AND data_type = 'uuid'
  ) THEN
    RETURN;
  END IF;
  EXECUTE format('ALTER TABLE public.%I ADD COLUMN id_new BIGINT', tbl);
  IF tbl = 'users' THEN
    UPDATE public.users u SET id_new = m.new_id FROM vl_user_id_map m WHERE u.id = m.old_id;
  ELSE
    EXECUTE format(
      'UPDATE public.%1$I t SET id_new = n.rn
       FROM (SELECT id, ROW_NUMBER() OVER (ORDER BY created_at NULLS LAST, id) AS rn FROM public.%1$I) n
       WHERE t.id = n.id', tbl);
  END IF;
  EXECUTE format('ALTER TABLE public.%I DROP COLUMN id', tbl);
  EXECUTE format('ALTER TABLE public.%I RENAME COLUMN id_new TO id', tbl);
  EXECUTE format('ALTER TABLE public.%I ALTER COLUMN id SET NOT NULL', tbl);
  EXECUTE format('ALTER TABLE public.%I ADD PRIMARY KEY (id)', tbl);
  EXECUTE format('ALTER TABLE public.%I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY', tbl);
  -- New rows continue after the highest existing number
  EXECUTE format(
    'SELECT setval(pg_get_serial_sequence(%L, ''id''), COALESCE((SELECT MAX(id) FROM public.%I), 1), (SELECT COUNT(*) > 0 FROM public.%I))',
    'public.' || tbl, tbl, tbl);
END
$f$;

DO $$
DECLARE
  fk RECORD;
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'users' AND column_name = 'id' AND data_type = 'uuid'
  ) THEN
    RETURN;
  END IF;

  RAISE NOTICE '[VibeLoop] Converting UUID keys to integer keys';

  CREATE TEMP TABLE vl_user_id_map ON COMMIT DROP AS
    SELECT id AS old_id, ROW_NUMBER() OVER (ORDER BY created_at NULLS LAST, id) AS new_id FROM public.users;

  -- Foreign keys to users are recreated below with the new column types
  FOR fk IN
    SELECT conrelid::regclass AS tbl, conname FROM pg_constraint
    WHERE contype = 'f' AND confrelid = 'public.users'::regclass
  LOOP
    EXECUTE format('ALTER TABLE %s DROP CONSTRAINT %I', fk.tbl, fk.conname);
  END LOOP;

  -- Admin actions on accounts already deleted keep the old ID in their details
  IF to_regclass('public.moderation_actions') IS NOT NULL THEN
    UPDATE public.moderation_actions
    SET details = COALESCE(details, '{}'::jsonb) || jsonb_build_object('legacyUserId', user_id::text)
    WHERE user_id NOT IN (SELECT old_id FROM vl_user_id_map);
  END IF;

  PERFORM pg_temp.vl_remap_user_column('match_history', 'user_id');
  PERFORM pg_temp.vl_remap_user_column('match_history', 'peer_id');
  PERFORM pg_temp.vl_remap_user_column('reports', 'reporter_id');
  PERFORM pg_temp.vl_remap_user_column('reports', 'reported_id');
  PERFORM pg_temp.vl_remap_user_column('reports', 'reviewed_by');
  PERFORM pg_temp.vl_remap_user_column('blocks', 'blocker_id');
  PERFORM pg_temp.vl_remap_user_column('blocks', 'blocked_id');
  PERFORM pg_temp.vl_remap_user_column('token_transactions', 'user_id');
  PERFORM pg_temp.vl_remap_user_column('messages', 'sender_id');
  PERFORM pg_temp.vl_remap_user_column('messages', 'recipient_id');
  PERFORM pg_temp.vl_remap_user_column('moderation_actions', 'admin_id');
  PERFORM pg_temp.vl_remap_user_column('moderation_actions', 'user_id');
  PERFORM pg_temp.vl_remap_user_column('payments', 'user_id');
  PERFORM pg_temp.vl_remap_user_column('friendships', 'requester_id');
  PERFORM pg_temp.vl_remap_user_column('friendships', 'addressee_id');

  -- Gift ledger entries name the other party inside metadata
  IF to_regclass('public.token_transactions') IS NOT NULL THEN
    UPDATE public.token_transactions t
    SET metadata = jsonb_set(t.metadata, '{recipientId}', to_jsonb(m.new_id::text))
    FROM vl_user_id_map m WHERE t.metadata->>'recipientId' = m.old_id::text;
    UPDATE public.token_transactions t
    SET metadata = jsonb_set(t.metadata, '{senderId}', to_jsonb(m.new_id::text))
    FROM vl_user_id_map m WHERE t.metadata->>'senderId' = m.old_id::text;
    -- Counterparties whose accounts were deleted: drop the dangling reference
    UPDATE public.token_transactions SET metadata = metadata - 'recipientId' WHERE metadata->>'recipientId' !~ '^[0-9]+$';
    UPDATE public.token_transactions SET metadata = metadata - 'senderId' WHERE metadata->>'senderId' !~ '^[0-9]+$';
  END IF;

  PERFORM pg_temp.vl_renumber('users');
  PERFORM pg_temp.vl_renumber('match_history');
  PERFORM pg_temp.vl_renumber('reports');
  PERFORM pg_temp.vl_renumber('token_transactions');
  PERFORM pg_temp.vl_renumber('messages');
  PERFORM pg_temp.vl_renumber('moderation_actions');
  PERFORM pg_temp.vl_renumber('payments');

  -- Restore the relationships the old UUID columns had
  IF to_regclass('public.match_history') IS NOT NULL THEN
    ALTER TABLE public.match_history
      ADD FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE,
      ADD FOREIGN KEY (peer_id) REFERENCES public.users(id) ON DELETE CASCADE;
  END IF;
  IF to_regclass('public.reports') IS NOT NULL THEN
    ALTER TABLE public.reports ALTER COLUMN reported_id SET NOT NULL;
    ALTER TABLE public.reports
      ADD FOREIGN KEY (reporter_id) REFERENCES public.users(id) ON DELETE SET NULL,
      ADD FOREIGN KEY (reported_id) REFERENCES public.users(id) ON DELETE CASCADE,
      ADD FOREIGN KEY (reviewed_by) REFERENCES public.users(id) ON DELETE SET NULL;
  END IF;
  IF to_regclass('public.blocks') IS NOT NULL THEN
    ALTER TABLE public.blocks ALTER COLUMN blocker_id SET NOT NULL, ALTER COLUMN blocked_id SET NOT NULL;
    ALTER TABLE public.blocks
      ADD PRIMARY KEY (blocker_id, blocked_id),
      ADD FOREIGN KEY (blocker_id) REFERENCES public.users(id) ON DELETE CASCADE,
      ADD FOREIGN KEY (blocked_id) REFERENCES public.users(id) ON DELETE CASCADE;
  END IF;
  IF to_regclass('public.token_transactions') IS NOT NULL THEN
    ALTER TABLE public.token_transactions ADD FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE CASCADE;
  END IF;
  IF to_regclass('public.messages') IS NOT NULL THEN
    ALTER TABLE public.messages ALTER COLUMN sender_id SET NOT NULL, ALTER COLUMN recipient_id SET NOT NULL;
    ALTER TABLE public.messages
      ADD FOREIGN KEY (sender_id) REFERENCES public.users(id) ON DELETE CASCADE,
      ADD FOREIGN KEY (recipient_id) REFERENCES public.users(id) ON DELETE CASCADE;
  END IF;
  IF to_regclass('public.moderation_actions') IS NOT NULL THEN
    ALTER TABLE public.moderation_actions ADD FOREIGN KEY (admin_id) REFERENCES public.users(id) ON DELETE SET NULL;
  END IF;
  IF to_regclass('public.payments') IS NOT NULL THEN
    ALTER TABLE public.payments ADD FOREIGN KEY (user_id) REFERENCES public.users(id) ON DELETE SET NULL;
  END IF;
  IF to_regclass('public.friendships') IS NOT NULL THEN
    ALTER TABLE public.friendships ALTER COLUMN requester_id SET NOT NULL, ALTER COLUMN addressee_id SET NOT NULL;
    ALTER TABLE public.friendships
      ADD PRIMARY KEY (requester_id, addressee_id),
      ADD CHECK (requester_id <> addressee_id),
      ADD FOREIGN KEY (requester_id) REFERENCES public.users(id) ON DELETE CASCADE,
      ADD FOREIGN KEY (addressee_id) REFERENCES public.users(id) ON DELETE CASCADE;
  END IF;
END $$;
