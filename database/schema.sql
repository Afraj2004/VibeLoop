-- VibeLoop schema. Safe to re-run: every statement is idempotent, and the
-- ALTER/DO blocks upgrade databases created from earlier versions of this file.
-- Keys are BIGINT identity columns. Databases created with UUID keys are converted
-- first by migrations/001_integer_ids.sql (migrate.js runs it before this file).

-- Core Users Table (guests are real rows so history, chat and wallets can reference them)
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(32) UNIQUE NOT NULL,
    email VARCHAR(255) UNIQUE,
    password_hash TEXT,
    is_guest BOOLEAN NOT NULL DEFAULT FALSE,
    avatar_url TEXT,
    gender VARCHAR(10) DEFAULT 'other',
    country_code VARCHAR(3) DEFAULT 'ALL',
    vibe_balance NUMERIC(10, 2) DEFAULT 0.00,
    is_verified BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

ALTER TABLE users ADD COLUMN IF NOT EXISTS is_guest BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE users ALTER COLUMN email DROP NOT NULL;
ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL;
ALTER TABLE users ALTER COLUMN country_code TYPE VARCHAR(3);
ALTER TABLE users ALTER COLUMN country_code SET DEFAULT 'ALL';

-- Wallet: earned_balance holds cash-out gift earnings; daily_* track the Meet-to-Earn cap
ALTER TABLE users ADD COLUMN IF NOT EXISTS earned_balance NUMERIC(12, 2) NOT NULL DEFAULT 0.00;
ALTER TABLE users ADD COLUMN IF NOT EXISTS daily_earned_tokens NUMERIC(5, 2) NOT NULL DEFAULT 0.00;
ALTER TABLE users ADD COLUMN IF NOT EXISTS last_earned_date DATE;

-- Trust & safety: consent records and temporary suspensions
ALTER TABLE users ADD COLUMN IF NOT EXISTS age_confirmed_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE users ADD COLUMN IF NOT EXISTS terms_accepted_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE users ADD COLUMN IF NOT EXISTS terms_version VARCHAR(16);
ALTER TABLE users ADD COLUMN IF NOT EXISTS banned_until TIMESTAMP WITH TIME ZONE;

-- Real-Time Match History (20-second threshold records)
CREATE TABLE IF NOT EXISTS match_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    peer_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    duration_seconds INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'match_history' AND column_name = 'matched_user_id'
    ) THEN
        ALTER TABLE match_history RENAME COLUMN matched_user_id TO peer_id;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS idx_match_history_user ON match_history(user_id, created_at DESC);

-- User reports (kept for manual review; drive automatic temporary bans)
CREATE TABLE IF NOT EXISTS reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    reported_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    reason VARCHAR(32) NOT NULL,
    details VARCHAR(500),
    reporter_ip VARCHAR(64),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_reports_reported ON reports(reported_id, created_at DESC);

-- Blocks: blocked pairs are never matched again
CREATE TABLE IF NOT EXISTS blocks (
    blocker_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    blocked_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    PRIMARY KEY (blocker_id, blocked_id)
);

-- Token Transactions
CREATE TABLE IF NOT EXISTS token_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    amount NUMERIC(10, 2) NOT NULL,
    transaction_type VARCHAR(32) NOT NULL,
    metadata JSONB,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_token_transactions_user ON token_transactions(user_id, created_at DESC);

-- Ephemeral Direct Messages (application keeps only the last 30 per pair)
CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    recipient_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    body VARCHAR(500) NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'messages' AND column_name = 'message_text'
    ) THEN
        ALTER TABLE messages RENAME COLUMN message_text TO body;
    END IF;
END $$;

ALTER TABLE messages ADD COLUMN IF NOT EXISTS is_read BOOLEAN NOT NULL DEFAULT FALSE;
CREATE INDEX IF NOT EXISTS idx_messages_chat_pair ON messages(sender_id, recipient_id, created_at DESC);

-- Admins (grant with: UPDATE users SET is_admin = TRUE WHERE email = 'you@example.com';)
ALTER TABLE users ADD COLUMN IF NOT EXISTS is_admin BOOLEAN NOT NULL DEFAULT FALSE;

-- Manual review state for reports
ALTER TABLE reports ADD COLUMN IF NOT EXISTS reviewed_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE reports ADD COLUMN IF NOT EXISTS reviewed_by BIGINT REFERENCES users(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_reports_open ON reports(reported_id) WHERE reviewed_at IS NULL;

-- Audit trail of admin decisions (user_id has no FK so the record survives account deletion;
-- it is NULL only for accounts deleted before the integer-key conversion, see details.legacyUserId)
CREATE TABLE IF NOT EXISTS moderation_actions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    user_id BIGINT,
    action VARCHAR(16) NOT NULL,
    details JSONB,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- VibeBoost: priority matching until this time
ALTER TABLE users ADD COLUMN IF NOT EXISTS boost_until TIMESTAMP WITH TIME ZONE;

-- VIBE purchases through Razorpay (one row per order; credited exactly once when captured)
CREATE TABLE IF NOT EXISTS payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    package_id VARCHAR(32) NOT NULL,
    vibe_amount NUMERIC(12, 2) NOT NULL,
    amount_paise INTEGER NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'INR',
    razorpay_order_id VARCHAR(64) UNIQUE NOT NULL,
    razorpay_payment_id VARCHAR(64),
    status VARCHAR(16) NOT NULL DEFAULT 'created' CHECK (status IN ('created', 'paid', 'failed')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    paid_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX IF NOT EXISTS idx_payments_user ON payments(user_id, created_at DESC);

-- New sessions start with 0 VIBE; registering grants a one-off bonus instead (see config/economy.js)
ALTER TABLE users ALTER COLUMN vibe_balance SET DEFAULT 0.00;

-- Profile photo (a small data URL, served by GET /api/avatars/:key). The reward is paid once.
ALTER TABLE users ADD COLUMN IF NOT EXISTS avatar_updated_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE users ADD COLUMN IF NOT EXISTS avatar_rewarded_at TIMESTAMP WITH TIME ZONE;

-- Friends: one row per pair, pending until the addressee accepts
CREATE TABLE IF NOT EXISTS friendships (
    requester_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    addressee_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    status VARCHAR(16) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    accepted_at TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY (requester_id, addressee_id),
    CHECK (requester_id <> addressee_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_friendships_pair
    ON friendships (LEAST(requester_id, addressee_id), GREATEST(requester_id, addressee_id));
CREATE INDEX IF NOT EXISTS idx_friendships_addressee ON friendships(addressee_id);

-- Likes: lifetime count of likes received in chats (one like per call, enforced by the signaling server)
ALTER TABLE users ADD COLUMN IF NOT EXISTS likes_received INTEGER NOT NULL DEFAULT 0;

-- Profile photo URLs use a random key, so photos can't be listed by counting user numbers
ALTER TABLE users ADD COLUMN IF NOT EXISTS avatar_key VARCHAR(32);
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_avatar_key ON users(avatar_key);
UPDATE users SET avatar_key = md5(random()::text || id::text) WHERE avatar_url IS NOT NULL AND avatar_key IS NULL;

-- Email verification: registered accounts can't sign in until the emailed code is entered.
-- Only a hash of the code is stored.
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE users ADD COLUMN IF NOT EXISTS verification_code_hash VARCHAR(64);
ALTER TABLE users ADD COLUMN IF NOT EXISTS verification_expires_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE users ADD COLUMN IF NOT EXISTS verification_attempts INTEGER NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN IF NOT EXISTS verification_sent_at TIMESTAMP WITH TIME ZONE;

-- Supabase's public Data API (anon / authenticated roles) must never see these tables.
-- RLS with no policies denies those roles everything; the server connects as the table owner,
-- which RLS does not restrict.
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE match_history ENABLE ROW LEVEL SECURITY;
ALTER TABLE reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE blocks ENABLE ROW LEVEL SECURITY;
ALTER TABLE token_transactions ENABLE ROW LEVEL SECURITY;
ALTER TABLE messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE moderation_actions ENABLE ROW LEVEL SECURITY;
ALTER TABLE payments ENABLE ROW LEVEL SECURITY;
ALTER TABLE friendships ENABLE ROW LEVEL SECURITY;
